// region-calibration.ts — единственный источник процентных констант,
// описывающих геометрию ячейки инвентаря (slot → container → icon/stars/
// number внутри контейнера).
//
// РАНЬШЕ одни и те же числа были продублированы (одними и теми же
// значениями, но независимо друг от друга) сразу в трёх местах:
//   - process-cell.ts          — containerTop/Bottom/X-инсеты, iconH/starsY/H
//   - digit-matching.ts       — NUMBER_STRIP_Y/H
//   - DigitCalibrationPage.tsx — DEFAULT_PCT (стартовые значения ползунков)
// Синхронность трёх копий держалась только на аккуратности при следующей
// правке — ничего структурно не мешало поправить процент в одном месте и
// забыть про два других. Теперь все три импортируют отсюда, менять — только
// здесь.
//
// ОТКАЛИБРОВАНО: 2026-07, на реальных скриншотах инвентаря (5★/3★/2★
// редкости предметов) через инструмент #/dev/digit-calibration — визуально
// проверено, что контейнер не обрезает число снизу и рамка "number" не
// цепляет звёзды (см. историю находок в шапке DigitCalibrationPage.tsx).
//
// ЕСЛИ ПОНАДОБИТСЯ ПЕРЕКАЛИБРОВАТЬ под новый тип скриншотов (другое
// разрешение/масштаб интерфейса игры): открой #/dev/digit-calibration,
// подвинь ползунки от текущих значений (не с нуля) и перенеси итоговые
// цифры сюда — это единственное место, которое нужно поменять.
//
// ЕДИНИЦЫ: доли от 0 до 1 (fraction) — так исторически их использовали
// useOcrProcess.ts/digit-matching.ts. DigitCalibrationPage (проценты 0-100
// в своих UI-полях) сам умножает на 100 при инициализации состояния.
// ============================================================================

